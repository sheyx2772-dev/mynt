// The catalogue is a design sample, not a directory of people.
//
// It shipped with thirteen invented officials: stock photographs of real,
// identifiable strangers, presented as named staff of real ministries and
// banks, carrying fabricated addresses on those bodies' own domains —
// j.tursunov@mf.uz, d.xolmatov@cbu.uz — and phone numbers in Tashkent's live
// range. Every one of those is gone. What is left is the organisation itself:
// its name, its sector, its published website, and nothing that belongs to a
// person. Real people reach this catalogue by claiming a handle and entering
// their own details, which is the product working rather than a demo pretending.

export interface Profile {
  id: string;
  category: "gov" | "ministry" | "bank" | "venture" | "startup" | "corp";
  categoryLabel: string;
  name: string;
  fullName: string;      // the organisation — this demo carries no people
  position: string;
  positionRu: string;
  organization: string;
  orgShort: string;
  department?: string;
  website?: string;   // only when the organisation actually publishes one
  avatar?: string;    // a real photograph, supplied by us for a named person
  bannerPosition?: string;  // square logos need a higher crop than photographs
  bannerFit?: "cover" | "contain";  // a small mark should not be upscaled to fill
  education?: string;  // as listed on the person's own profile
  coverColor: string;
  coverAccent: string;
  logoText: string;
  socials: { type: string; handle: string }[];
  tags: string[];
  verified: boolean;

  // ── what ProfileCardV2 draws, where a record carries it ──────────────────
  //
  // Which of the seventeen designs a profile is drawn in. Absent means the
  // original card.
  template?:
    | "premium" | "gradient" | "minimal" | "glass" | "stripe"
    | "feminine" | "terminal" | "comic" | "sport" | "kids"
    | "nature" | "historical" | "country" | "brand"
    | "chef" | "artist" | "musician";
  /** The six colours a V2 design paints itself from. */
  v2?: { bg1: string; bg2: string; accent: string; text: string; sub: string; tag: string };
  /** Per-design extras: a flag, a shirt number, a speciality. */
  extra?: {
    flag?: string; country?: string; brandName?: string; brandColor?: string;
    logoChar?: string; specialty?: string; jerseyNum?: string;
  };

  // Optional, and empty on every organisation in this file — see the note at
  // the top. The V2 designs draw a contact row when these are present, and the
  // catalogue has nobody to put in it: inventing a person's telephone number
  // and an address on a real body's own domain is the thing that was removed.
  phone?: string;
  email?: string;
  address?: string;
  gender?: "male" | "female";
  age?: number;
}

